-- Admin-only CRM usage evidence across desktop and mobile.
-- Existing CRM records are untouched; this adds an append-only audit trail.

create table if not exists public.crm_usage_sessions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references public.bd_team_members(id) on delete cascade,
  session_key text not null,
  device_type text not null check (device_type in ('desktop', 'mobile', 'tablet', 'unknown')),
  browser text,
  operating_system text,
  current_path text,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  unique (user_id, session_key)
);

create index if not exists crm_usage_sessions_user_seen_idx
  on public.crm_usage_sessions (user_id, last_seen_at desc);

create table if not exists public.crm_usage_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references public.bd_team_members(id) on delete cascade,
  event_type text not null,
  action text not null,
  entity_type text,
  entity_id uuid,
  entity_label text,
  device_type text not null default 'unknown'
    check (device_type in ('desktop', 'mobile', 'tablet', 'unknown')),
  browser text,
  operating_system text,
  route text,
  source text not null default 'client' check (source in ('client', 'database')),
  metadata jsonb not null default '{}'::jsonb,
  occurred_at timestamptz not null default now()
);

create index if not exists crm_usage_events_user_time_idx
  on public.crm_usage_events (user_id, occurred_at desc);
create index if not exists crm_usage_events_time_idx
  on public.crm_usage_events (occurred_at desc);
create index if not exists crm_usage_events_type_time_idx
  on public.crm_usage_events (event_type, occurred_at desc);

alter table public.crm_usage_sessions enable row level security;
alter table public.crm_usage_events enable row level security;

grant select, insert, update on public.crm_usage_sessions to authenticated;
grant select, insert on public.crm_usage_events to authenticated;
grant usage, select on sequence public.crm_usage_events_id_seq to authenticated;
grant all on public.crm_usage_sessions, public.crm_usage_events to service_role;
grant all on sequence public.crm_usage_events_id_seq to service_role;

drop policy if exists "Members manage own usage sessions" on public.crm_usage_sessions;
drop policy if exists "Admins view all usage sessions" on public.crm_usage_sessions;
create policy "Members manage own usage sessions"
on public.crm_usage_sessions for all to authenticated
using (user_id = (select auth.uid()) and private.crm_access_approved())
with check (user_id = (select auth.uid()) and private.crm_access_approved());
create policy "Admins view all usage sessions"
on public.crm_usage_sessions for select to authenticated
using (private.crm_access_admin());

drop policy if exists "Members add own client usage events" on public.crm_usage_events;
drop policy if exists "Members view own usage events" on public.crm_usage_events;
drop policy if exists "Admins view all usage events" on public.crm_usage_events;
create policy "Members add own client usage events"
on public.crm_usage_events for insert to authenticated
with check (
  user_id = (select auth.uid())
  and source = 'client'
  and private.crm_access_approved()
);
create policy "Members view own usage events"
on public.crm_usage_events for select to authenticated
using (user_id = (select auth.uid()) and private.crm_access_approved());
create policy "Admins view all usage events"
on public.crm_usage_events for select to authenticated
using (private.crm_access_admin());

create or replace function private.log_crm_record_activity()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor_id uuid := auth.uid();
  row_data jsonb;
  old_data jsonb;
  event_name text;
  action_name text;
  label_value text;
  current_device text := 'unknown';
  current_browser text;
  current_os text;
  current_route text;
  extra jsonb := '{}'::jsonb;
begin
  if actor_id is null or not private.crm_access_approved() then
    return coalesce(new, old);
  end if;

  row_data := case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end;
  old_data := case when tg_op = 'UPDATE' then to_jsonb(old) else '{}'::jsonb end;

  select session.device_type, session.browser, session.operating_system, session.current_path
    into current_device, current_browser, current_os, current_route
  from public.crm_usage_sessions session
  where session.user_id = actor_id
    and session.last_seen_at >= now() - interval '30 minutes'
  order by session.last_seen_at desc
  limit 1;

  current_device := coalesce(current_device, 'unknown');
  label_value := coalesce(
    nullif(row_data ->> 'contact_name', ''),
    nullif(row_data ->> 'company_name', ''),
    nullif(row_data ->> 'name', ''),
    nullif(row_data ->> 'deal_name', ''),
    nullif(row_data ->> 'title', ''),
    nullif(row_data ->> 'course_topic', ''),
    nullif(row_data ->> 'employee_name', ''),
    nullif(row_data ->> 'phone_number', ''),
    'CRM record'
  );

  event_name := case tg_op
    when 'INSERT' then 'record_created'
    when 'UPDATE' then 'record_updated'
    when 'DELETE' then 'record_deleted'
  end;
  action_name := initcap(lower(tg_op)) || ' ' || replace(tg_table_name, '_', ' ');

  if tg_table_name = 'activities' then
    extra := extra || jsonb_build_object(
      'activity_type', row_data ->> 'activity_type',
      'status', row_data ->> 'status'
    );
  end if;

  if tg_table_name = 'leads'
     and tg_op = 'UPDATE'
     and lower(coalesce(old_data ->> 'status', '')) is distinct from
         lower(coalesce(row_data ->> 'status', ''))
  then
    if lower(coalesce(row_data ->> 'status', '')) = 'converted' then
      event_name := 'lead_converted';
      action_name := 'Converted lead to corporate client';
    else
      event_name := 'lead_status_changed';
      action_name := 'Changed lead status';
    end if;
    extra := extra || jsonb_build_object(
      'from_status', old_data ->> 'status',
      'to_status', row_data ->> 'status'
    );
  elsif tg_table_name = 'leads'
        and tg_op = 'UPDATE'
        and coalesce(old_data ->> 'call_status', '') is distinct from
            coalesce(row_data ->> 'call_status', '')
  then
    event_name := 'call_status_changed';
    action_name := 'Changed call status';
    extra := extra || jsonb_build_object(
      'from_status', old_data ->> 'call_status',
      'to_status', row_data ->> 'call_status'
    );
  elsif tg_table_name = 'activities'
        and tg_op = 'UPDATE'
        and coalesce(old_data ->> 'status', '') is distinct from
            coalesce(row_data ->> 'status', '')
        and row_data ->> 'status' = 'Completed'
  then
    event_name := 'activity_completed';
    action_name := 'Completed ' || lower(coalesce(row_data ->> 'activity_type', 'activity'));
  elsif tg_table_name = 'daily_eod_reports' and tg_op = 'INSERT' then
    event_name := 'eod_submitted';
    action_name := 'Submitted daily EOD';
  end if;

  insert into public.crm_usage_events (
    user_id, event_type, action, entity_type, entity_id, entity_label,
    device_type, browser, operating_system, route, source, metadata
  )
  values (
    actor_id,
    event_name,
    action_name,
    tg_table_name,
    nullif(row_data ->> 'id', '')::uuid,
    label_value,
    current_device,
    current_browser,
    current_os,
    current_route,
    'database',
    extra
  );

  return coalesce(new, old);
end;
$$;

revoke all on function private.log_crm_record_activity()
  from public, anon, authenticated;

do $$
declare
  tracked_table text;
begin
  foreach tracked_table in array array[
    'leads', 'accounts', 'deals', 'activities', 'call_logs', 'contacts',
    'poa_entries', 'daily_eod_reports', 'training_requests',
    'training_batches', 'trainers'
  ]
  loop
    if to_regclass(format('public.%I', tracked_table)) is null then
      continue;
    end if;
    execute format('drop trigger if exists crm_usage_audit on public.%I', tracked_table);
    execute format(
      'create trigger crm_usage_audit after insert or update or delete on public.%I for each row execute function private.log_crm_record_activity()',
      tracked_table
    );
  end loop;
end
$$;
